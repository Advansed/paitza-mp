const DOCUMENTS: Record<AppLocale, PrivacyDocumentContent> = { ru, en, zh }

export function privacyLocale(language: string | undefined): AppLocale {
  const code = (language || 'ru').slice(0, 2)
  if (code === 'en' || code === 'zh') return code
  return 'ru'
}

export function privacyDocument(language: string | undefined): PrivacyDocumentContent {
  return DOCUMENTS[privacyLocale(language)]
}
